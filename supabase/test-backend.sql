-- All test data is rolled back, including the temporary Auth users.
begin;
do $$
declare
  autor uuid := gen_random_uuid();
  solicitante uuid := gen_random_uuid();
  tercero uuid := gen_random_uuid();
  objeto_id uuid;
  otro_objeto_id uuid;
  busqueda_id uuid;
  reclamo_id uuid;
  resultado jsonb;
  bloqueado boolean;
begin
  insert into auth.users (id) values (autor), (solicitante), (tercero);
  perform set_config('request.jwt.claim.sub', autor::text, true);
  resultado := public.api_mutar('crear_objeto', '{"titulo":"Llaves azules","categoria":"llaves","descripcion":"Llaves encontradas","fecha_hallazgo":"2026-10-01","lugar_hallazgo":"Biblioteca","tipo_entrega":"coordinar_contacto"}', null);
  objeto_id := (resultado->>'id')::uuid;
  if resultado->>'publicado_por' <> autor::text then raise exception 'autor incorrecto'; end if;
  resultado := public.api_mutar('crear_objeto', '{"titulo":"Otro objeto","categoria":"otros","descripcion":"Objeto encontrado","fecha_hallazgo":"2026-10-01","lugar_hallazgo":"Biblioteca","tipo_entrega":"coordinar_contacto"}', null);
  otro_objeto_id := (resultado->>'id')::uuid;
  perform set_config('request.jwt.claim.sub', solicitante::text, true);
  resultado := public.api_mutar('crear_busqueda', '{"categoria":"llaves","descripcion":"Perdí unas llaves"}', null);
  busqueda_id := (resultado->>'id')::uuid;
  resultado := public.api_mutar('crear_reclamacion', jsonb_build_object('objeto_id',objeto_id, 'busqueda_id',busqueda_id, 'prueba_propiedad','Son mis llaves azules'), null);
  reclamo_id := (resultado->>'id')::uuid;
  bloqueado := false;
  begin perform public.api_mutar('crear_reclamacion', jsonb_build_object('objeto_id',objeto_id, 'prueba_propiedad','Son mis llaves azules'), null);
  exception when sqlstate 'PT409' then bloqueado := true; end;
  if not bloqueado then raise exception 'permitió reclamos duplicados'; end if;
  bloqueado := false;
  begin perform public.api_mutar('gestionar_reclamacion', '{"estado":"aprobada"}', reclamo_id);
  exception when sqlstate 'PT403' then bloqueado := true; end;
  if not bloqueado then raise exception 'permitió gestionar a un usuario ajeno'; end if;
  bloqueado := false;
  begin perform public.api_mutar('eliminar_objeto', '{}', otro_objeto_id);
  exception when sqlstate 'PT403' then bloqueado := true; end;
  if not bloqueado then raise exception 'permitió eliminar a un usuario ajeno'; end if;
  perform set_config('request.jwt.claim.sub', autor::text, true);
  resultado := public.api_mutar('gestionar_reclamacion', '{"estado":"aprobada"}', reclamo_id);
  if resultado->>'estado' <> 'aprobada' or (select estado from public.objetos where id=objeto_id) <> 'en_recuperacion' then raise exception 'aprobación incorrecta'; end if;
  resultado := public.api_mutar('gestionar_reclamacion', '{"estado":"entregada"}', reclamo_id);
  if resultado->>'estado' <> 'entregada' or (select estado from public.objetos where id=objeto_id) <> 'entregado' then raise exception 'entrega incorrecta'; end if;
  bloqueado := false;
  begin perform public.api_mutar('eliminar_objeto', '{}', objeto_id);
  exception when sqlstate 'PT409' then bloqueado := true; end;
  if not bloqueado then raise exception 'permitió eliminar objeto con reclamaciones'; end if;
  resultado := public.api_mutar('eliminar_objeto', '{}', otro_objeto_id);
  if resultado->>'eliminado' <> 'true' then raise exception 'eliminación incorrecta'; end if;
  if has_function_privilege('anon', 'public.api_mutar(text,jsonb,uuid)', 'execute') then raise exception 'anon puede modificar'; end if;
  perform set_config('role', 'authenticated', true);
  resultado := public.api_mutar('crear_busqueda', '{"categoria":"llaves","descripcion":"Segunda búsqueda"}', null);
  if resultado->>'usuario_id' <> autor::text then raise exception 'RPC inaccesible como authenticated'; end if;
  if (select count(*) from public.reclamaciones where id = reclamo_id) <> 1 then raise exception 'el autor no puede leer la reclamación'; end if;
  perform set_config('request.jwt.claim.sub', solicitante::text, true);
  if (select count(*) from public.reclamaciones where id = reclamo_id) <> 1 then raise exception 'el solicitante no puede leer la reclamación'; end if;
  perform set_config('request.jwt.claim.sub', tercero::text, true);
  if (select count(*) from public.reclamaciones where id = reclamo_id) <> 0 then raise exception 'un tercero puede leer la reclamación'; end if;
  perform set_config('role', 'none', true);
end;
$$;
rollback;
